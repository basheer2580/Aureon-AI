create or replace function public.redeem_premium_coupon(
    p_user_id uuid,
    p_coupon_hash text
) returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
    v_hash text;
begin
    update public.premium_coupons
       set redeemed_by = p_user_id,
           redeemed_at = now()
     where coupon_hash = p_coupon_hash
       and redeemed_at is null
    returning coupon_hash into v_hash;

    if v_hash is null then
        return false;
    end if;

    insert into public.account_profiles (user_id, password_initialized)
    values (p_user_id, true)
    on conflict (user_id) do nothing;

    update public.account_profiles
       set is_premium_whitelisted = true,
           updated_at = now()
     where user_id = p_user_id;
    return true;
end;
$$;

create or replace function public.renew_daily_credits(
    p_user_id uuid
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_profile public.account_profiles%rowtype;
    v_credits integer;
    v_balance bigint;
    v_added bigint;
begin
    select * into v_profile
      from public.account_profiles
     where user_id = p_user_id
     for update;
    if not found then
        return jsonb_build_object('error', 'account_not_found');
    end if;
    if not v_profile.active or v_profile.is_premium_whitelisted then
        return jsonb_build_object(
            'renewed', false,
            'credit_balance', v_profile.credit_balance,
            'reason', 'not_eligible'
        );
    end if;
    if v_profile.last_daily_renewal = current_date then
        return jsonb_build_object(
            'renewed', false,
            'credit_balance', v_profile.credit_balance
        );
    end if;
    select (config_value->>'daily_renewal_credits')::integer
      into v_credits
      from public.system_config
     where config_key = 'standard_plan';
    v_credits := coalesce(v_credits, 1000);
    update public.account_profiles
       set credit_balance = least(20000::bigint, credit_balance + v_credits),
           last_daily_renewal = current_date,
           updated_at = now()
     where user_id = p_user_id
    returning credit_balance into v_balance;
    v_added := greatest(0, least(v_credits::bigint, 20000::bigint - v_profile.credit_balance));
    return jsonb_build_object(
        'renewed', true,
        'credits_added', v_added,
        'credit_balance', v_balance
    );
end;
$$;

create or replace function public.deduct_task_credits(
    p_user_id uuid
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_profile public.account_profiles%rowtype;
    v_cost integer;
    v_balance bigint;
begin
    select * into v_profile
      from public.account_profiles
     where user_id = p_user_id
     for update;
    if not found then
        return jsonb_build_object('error', 'account_not_found');
    end if;
    if v_profile.is_premium_whitelisted then
        return jsonb_build_object(
            'deducted', 0,
            'credit_balance', v_profile.credit_balance,
            'is_premium_whitelisted', true
        );
    end if;
    select (config_value->>'task_credit_cost')::integer
      into v_cost
      from public.system_config
     where config_key = 'standard_plan';
    v_cost := coalesce(v_cost, 50);
    if v_profile.credit_balance < v_cost then
        return jsonb_build_object(
            'error', 'insufficient_credits',
            'credit_balance', v_profile.credit_balance
        );
    end if;
    update public.account_profiles
       set credit_balance = credit_balance - v_cost,
           updated_at = now()
     where user_id = p_user_id
    returning credit_balance into v_balance;
    return jsonb_build_object(
        'deducted', v_cost,
        'credit_balance', v_balance,
        'is_premium_whitelisted', false
    );
end;
$$;

create or replace function public.claim_mock_domain(
    p_domain text,
    p_user_id uuid,
    p_project_name text,
    p_site_path text,
    p_standard_limit integer
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_premium boolean;
    v_active_count integer;
    v_rows integer;
begin
    select is_premium_whitelisted into v_premium
      from public.account_profiles
     where user_id = p_user_id
     for update;
    if not found then
        return jsonb_build_object('error', 'account_not_found');
    end if;
    if not v_premium then
        select count(*) into v_active_count
          from public.domain_claims
         where user_id = p_user_id and active;
        if v_active_count >= p_standard_limit then
            return jsonb_build_object('error', 'active_domain_limit');
        end if;
    end if;

    insert into public.domain_claims (domain, user_id, project_name, site_path)
    values (lower(p_domain), p_user_id, p_project_name, p_site_path)
    on conflict (domain) do nothing;
    get diagnostics v_rows = row_count;
    if v_rows = 0 then
        return jsonb_build_object('error', 'domain_unavailable');
    end if;
    return jsonb_build_object('success', true, 'domain', lower(p_domain));
end;
$$;

create or replace function public.admin_login_allowed(
    p_username text
) returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
    v_attempt public.admin_login_attempts%rowtype;
begin
    insert into public.admin_login_attempts (username)
    values (lower(p_username))
    on conflict (username) do nothing;
    select * into v_attempt
      from public.admin_login_attempts
     where username = lower(p_username)
     for update;
    if v_attempt.locked_until is not null and v_attempt.locked_until > now() then
        return false;
    end if;
    if v_attempt.window_started_at < now() - interval '15 minutes' then
        update public.admin_login_attempts
           set window_started_at = now(),
               failed_attempts = 0,
               locked_until = null
         where username = lower(p_username);
    end if;
    return true;
end;
$$;

create or replace function public.record_admin_login(
    p_username text,
    p_success boolean
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_attempt public.admin_login_attempts%rowtype;
begin
    insert into public.admin_login_attempts (username)
    values (lower(p_username))
    on conflict (username) do nothing;
    select * into v_attempt
      from public.admin_login_attempts
     where username = lower(p_username)
     for update;
    if p_success then
        delete from public.admin_login_attempts where username = lower(p_username);
        return;
    end if;
    if v_attempt.window_started_at < now() - interval '15 minutes' then
        update public.admin_login_attempts
           set window_started_at = now(),
               failed_attempts = 1,
               locked_until = null
         where username = lower(p_username);
    else
        update public.admin_login_attempts
           set failed_attempts = failed_attempts + 1,
               locked_until = case
                   when failed_attempts + 1 >= 5 then now() + interval '15 minutes'
                   else locked_until
               end
         where username = lower(p_username);
    end if;
end;
$$;

create or replace function public.run_daily_maintenance()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_daily_credits integer;
    v_credited_accounts integer := 0;
    v_trackers_reset integer := 0;
    v_balances_capped integer := 0;
    v_credits_added bigint := 0;
begin
    select (config_value->>'daily_renewal_credits')::integer
      into v_daily_credits
      from public.system_config
     where config_key = 'standard_plan';

    if v_daily_credits is null or v_daily_credits < 0 then
        raise exception 'standard_plan.daily_renewal_credits must be configured as a non-negative integer';
    end if;

    with eligible as (
        select user_id, credit_balance
          from public.account_profiles
         where active = true
           and is_premium_whitelisted = false
           and last_daily_renewal is distinct from current_date
         for update
    ),
    updated as (
        update public.account_profiles as profiles
           set credit_balance = least(20000::bigint, eligible.credit_balance + v_daily_credits),
               last_daily_renewal = current_date,
               updated_at = now()
          from eligible
         where profiles.user_id = eligible.user_id
        returning
            least(v_daily_credits::bigint, greatest(0, 20000::bigint - eligible.credit_balance)) as added,
            (eligible.credit_balance + v_daily_credits > 20000) as capped
    )
    select count(*)::integer,
           coalesce(sum(added), 0),
           count(*) filter (where capped)::integer
      into v_credited_accounts, v_credits_added, v_balances_capped
      from updated;

    update public.daily_usage_trackers
       set photo_count = 0,
           video_count = 0,
           cross_agent_log_count = 0,
           updated_at = now()
     where photo_count <> 0
        or video_count <> 0
        or cross_agent_log_count <> 0;
    get diagnostics v_trackers_reset = row_count;

    return jsonb_build_object(
        'success', true,
        'run_date', current_date,
        'daily_renewal_credits', v_daily_credits,
        'credit_cap', 20000,
        'credited_accounts', v_credited_accounts,
        'credits_added', v_credits_added,
        'balances_capped', v_balances_capped,
        'trackers_reset', v_trackers_reset
    );
end;
$$;

